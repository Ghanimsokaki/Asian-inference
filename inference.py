def generate_colab_notebook(model_name: str, base_model: str,
                            output_repo: str, dataset_rows: list,
                            hf_token: str = "",
                            epochs: int = 3, lr: float = 2e-4,
                            max_length: int = 512, batch_size: int = 4) -> str:
    """Returns a .ipynb JSON string ready to open in Google Colab."""
    dataset_json = json.dumps(dataset_rows[:500], indent=2)  # cap to 500 rows in nb
    nb = COLAB_TEMPLATE.format(
        model_name    = model_name,
        base_model    = base_model,
        output_repo   = output_repo,
        hf_token      = hf_token or "YOUR_HF_WRITE_TOKEN",
        dataset_rows  = len(dataset_rows),
        num_cols      = len(dataset_rows[0]) if dataset_rows else 0,
        dataset_json  = dataset_json,
        epochs        = epochs,
        lr            = lr,
        max_length    = max_length,
        batch_size    = batch_size,
    )
    return nb
