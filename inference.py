HF_API = "https://api-inference.huggingface.co/models"

# ── Inference ───────────────────────────────────────────────────────
def call_hf(repo_id: str, prompt: str, hf_token: str = None,
            max_new: int = 512, temperature: float = 0.7) -> str:
    """Call any HuggingFace model by repo_id with optional user-supplied token."""
    token   = hf_token or HF_TOKEN
    headers = {"Authorization": f"Bearer {token}"}
    payload = {
        "inputs": prompt,
        "parameters": {"max_new_tokens": max_new, "temperature": temperature,
                       "return_full_text": False},
    }
    try:
        r = requests.post(f"{HF_API}/{repo_id}", headers=headers, json=payload, timeout=60)
        r.raise_for_status()
        result = r.json()
        if isinstance(result, list) and result:
            return result[0].get("generated_text", "").strip()
        if isinstance(result, dict) and "generated_text" in result:
            return result["generated_text"].strip()
        return str(result)
    except requests.exceptions.HTTPError as e:
        if e.response.status_code == 503:
            return "[MODEL_LOADING] Model is warming up — try again in 20 seconds."
        return f"[HTTP {e.response.status_code}] {e}"
    except Exception as e:
        return f"[ERROR] {e}"

def call_gemby(prompt: str) -> str:
    """Default: use Gemby Agent 3B."""
    return call_hf("Hwiiiiiiii/gemby-agent-3b", prompt)

def generate_dataset_rows(topic: str, num_rows: int,
                          columns: list, style: str,
                          model_repo: str = None,
                          user_hf_token: str = None,
                          progress_cb=None) -> list:
    repo = model_repo or "Hwiiiiiyyy/gemby-agent-3b"
    rows = []
    col_str = ", ".join(columns)
    for i in range(num_rows):
        if progress_cb:
            progress_cb(i, num_rows)
        prompt = (
            f"Generate ONE realistic row for a {style} dataset about: {topic}.\n"
            f"Columns: {col_str}\n"
            f"Row {i+1}/{num_rows}.\n"
            f"Respond ONLY with a JSON object using exactly these keys: "
            + "{ " + ", ".join(f'"{c}": "..."' for c in columns) + " }"
        )
        raw = call_hf(repo, prompt, hf_token=user_hf_token)
        try:
            m   = re.search(r'\{.*?\}', raw, re.DOTALL)
            row = json.loads(m.group()) if m else {c: f"sample_{i+1}" for c in columns}
        except Exception:
            row = {c: f"sample_{i+1}" for c in columns}
        rows.append(row)
    return rows

